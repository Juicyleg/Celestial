pub fn advance_units(c: char) -> Option<u16> {
    let cp = c as u32;
    if (32..127).contains(&cp) {
        return Some(ASCII[(cp - 32) as usize]);
    }
    EXTRA
        .binary_search_by_key(&cp, |e| e.0)
        .ok()
        .map(|i| EXTRA[i].1)
}

pub fn width(s: &str, size: f32) -> f32 {
    let mut w = 0.0;
    for c in s.chars() {
        w += match advance_units(c) {
            Some(a) => a as f32 / UPM * size,
            None => 0.6 * size,
        };
    }
    w
}
